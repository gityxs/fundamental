var cnItem = function (text, node) {

    if (typeof (text) != "string")
        return text;
	let textori = text;
    //处理前缀
    let text_prefix = "";
    for (let prefix in cnPrefix) {
        if (text.substr(0, prefix.length) === prefix) {
            text_prefix += cnPrefix[prefix];
            text = text.substr(prefix.length);
        }
    }
    //处理后缀
    let text_postfix = "";
    for (let postfix in cnPostfix) {
        if (text.substr(-postfix.length) === postfix) {
            text_postfix = cnPostfix[postfix] + text_postfix;
            text = text.substr(0, text.length - postfix.length);
        }
    }
    //处理正则后缀
    let text_reg_exclude_postfix = "";
    for (let reg of cnExcludePostfix) {
        let result = text.match(reg);
        if (result) {
            text_reg_exclude_postfix = result[0] + text_reg_exclude_postfix;
            text = text.substr(0, text.length - result[0].length);
        }
    }

    //检验字典是否可存
    if (!cnItems._OTHER_) cnItems._OTHER_ = [];

    //检查是否排除
    for (let reg of cnExcludeWhole) {
        if (reg.test(text)) {
            return text_prefix + text + text_reg_exclude_postfix + text_postfix;;
        }
    }

    //尝试正则替换
    for (let [key, value] of cnRegReplace.entries()) {
        if (key.test(text)) {
            return text_prefix + text.replace(key, value) + text_reg_exclude_postfix + text_postfix;
        }
    }

    //遍历尝试匹配
    for (let i in cnItems) {
        //字典已有词汇或译文、且译文不为空，则返回译文
        if (typeof(cnItems[i]) == "string" && (text == i || text == cnItems[i])){
			return text_prefix + cnItems[i] + text_reg_exclude_postfix + text_postfix;
		} else if ( typeof(cnItems[i]) == "object" && text == i ){
			let result = cnItemByTag(i, cnItems[i], node, textori);
			if (result != null){
				return text_prefix + result + text_reg_exclude_postfix + text_postfix;
			} else {
				CNITEM_DEBUG && console.log({text:i, cnitem:cnItems[i], node});
			}
		} else {
            // continue;
        }
    }

    //调整收录的词条，0=收录原文，1=收录去除前后缀的文本
    let save_cfg = 1;
    let save_text = save_cfg ? text : textori;
    //遍历生词表是否收录
    for (
        let i = 0; i < cnItems._OTHER_.length; i++
    ) {
        //已收录则直接返回
        if (save_text == cnItems._OTHER_[i])
            return text_prefix + text + text_reg_exclude_postfix + text_postfix;
    }

    if (cnItems._OTHER_.length < 1000) {
        //未收录则保存
        cnItems._OTHER_.push(save_text);
        cnItems._OTHER_.sort(
            function (a, b) {
                return a.localeCompare(b)
            }
        );
    }

    //开启生词打印
        CNITEM_DEBUG && console.log(
            '有需要汉化的英文：', text
        );

    //返回生词字串
    return text_prefix + text + text_reg_exclude_postfix + text_postfix;
};

transTaskMgr = {
    tasks: [],
    addTask: function (node, attr, text) {
        this.tasks.push({
            node,
            attr,
            text
        })
    },
    doTask: function () {
        let task = null;
        while (task = this.tasks.pop())
            task.node[task.attr] = task.text;
    },
}

function TransSubTextNode(node) {
    if (node.childNodes.length > 0) {
        for (let subnode of node.childNodes) {
            if (subnode.nodeName === "#text") {
                let text = subnode.textContent;
                let cnText = cnItem(text, subnode);
                cnText !== text && transTaskMgr.addTask(subnode, 'textContent', cnText);
                //console.log(subnode);
            } else if (subnode.nodeName !== "SCRIPT" && subnode.nodeName !== "STYLE" && subnode.nodeName !== "TEXTAREA") {
                if (!subnode.childNodes || subnode.childNodes.length == 0) {
                    let text = subnode.innerText;
                    let cnText = cnItem(text, subnode);
                    cnText !== text && transTaskMgr.addTask(subnode, 'innerText', cnText);
                    //console.log(subnode);
                } else {
                    TransSubTextNode(subnode);
                }
            } else {
                // do nothing;
            }
        }
    }
}

! function () {
    console.log("加载汉化模块");

    let observer_config = {
        attributes: false,
        characterData: true,
        childList: true,
        subtree: true
    };
    let targetNode = document.body;
    //汉化静态页面内容
    TransSubTextNode(targetNode);
    transTaskMgr.doTask();
    //监听页面变化并汉化动态内容
    let observer = new MutationObserver(function (e) {
        //window.beforeTransTime = performance.now();
        observer.disconnect();
        for (let mutation of e) {
            if (mutation.target.nodeName === "SCRIPT"|| mutation.target.nodeName === "STYLE" || mutation.target.nodeName === "TEXTAREA") continue;
			if (mutation.target.nodeName === "#text") {
                mutation.target.textContent = cnItem(mutation.target.textContent, mutation.target);
            } else if (!mutation.target.childNodes || mutation.target.childNodes.length == 0) {
                mutation.target.innerText = cnItem(mutation.target.innerText, mutation.target);
            } else if (mutation.addedNodes.length > 0) {
                for (let node of mutation.addedNodes) {
                    if (node.nodeName === "#text") {
                        node.textContent = cnItem(node.textContent, node);
                        //console.log(node);
                    } else if (node.nodeName !== "SCRIPT" && node.nodeName !== "STYLE" && node.nodeName !== "TEXTAREA") {
                        if (!node.childNodes || node.childNodes.length == 0) {
							if (node.innerText)
								node.innerText = cnItem(node.innerText, node);
                        } else {
                            TransSubTextNode(node);
                        }
                    }
                }
            }
        }
        transTaskMgr.doTask();
        observer.observe(targetNode, observer_config);
        //window.afterTransTime = performance.now();
        //console.log("捕获到页面变化并执行汉化，耗时" + (afterTransTime - beforeTransTime) + "毫秒");
    });
    observer.observe(targetNode, observer_config);
}();

/* ==== 多行文本逐行汉化补丁（由汉化补全脚本追加） ==== */
(function () {
    var baseCnItem = cnItem;
    var LATIN = /[A-Za-z]/;
    // 仅当整段确实被翻译成中文时才算数：
    // 否则像 " Cosmons" 这类后缀替换会让整段被误判为“已翻译”，从而跳过逐行汉化。
    function translatedEnough(s) {
        var cjk = s.match(/[\u4e00-\u9fff]/g);
        if (!cjk || cjk.length < 2) return false;
        var compact = s.replace(/\s+/g, '');
        return cjk.length / Math.max(1, compact.length) >= 0.15;
    }
    function transLine(line, node) {
        if (!line || !LATIN.test(line)) return line;
        var m = line.match(/^(\s*)([\s\S]*?)(\s*)$/);
        var lead = m[1], core = m[2], tail = m[3];
        if (!core) return line;
        var out = baseCnItem(core, node);
        return out === core ? line : lead + out + tail;
    }
    cnItem = function (text, node) {
        if (typeof text !== 'string') return text;
        var norm = text.indexOf('\r') === -1 ? text : text.replace(/\r\n/g, '\n');
        var whole = baseCnItem(norm, node);
        if (whole !== norm && translatedEnough(whole)) return whole;
        if (norm.indexOf('\n') === -1) return whole;
        var lines = norm.split('\n');
        var changed = false;
        for (var i = 0; i < lines.length; i++) {
            var t = transLine(lines[i], node);
            if (t !== lines[i]) { lines[i] = t; changed = true; }
        }
        return changed ? lines.join('\n') : whole;
    };
})();

/* ==== 合并按钮说明：真假真空提示整体汉化 ====
   这两句是带内联 <span> 的 HTML，会被拆成多个文本节点各自匹配，
   从而出现「返回到假Vacuum state by Merging星系」「真空decaying into its 真state」这类中英混杂。
   这里按整段识别后整体替换，颜色用的 span 保持原样。 */
(function () {
    var RULES = [
        {
            test: /Vacuum state by|there are no direct rewards/,
            html: '通过把 <span class="grayText">星系</span> <span class="darkvioletText">合并</span> 在一起，可返回到 <span class="redText">假</span> 真空状态，但没有直接奖励'
        },
        {
            test: /decaying into its|will result in/,
            html: '试图把 <span class="grayText">星系</span> <span class="darkvioletText">合并</span> 在一起，会导致 <span class="orchidText">真空</span> 衰减到 <span class="greenText">真</span> 状态'
        }
    ];
    function fix() {
        var el = document.getElementById('mergeFalse');
        if (!el) return;
        var txt = el.textContent;
        for (var i = 0; i < RULES.length; i++) {
            if (RULES[i].test.test(txt)) { el.innerHTML = RULES[i].html; return; }
        }
    }
    function start() {
        var el = document.getElementById('mergeFalse');
        if (!el) return;
        new MutationObserver(fix).observe(el, { childList: true, subtree: true, characterData: true });
        fix();
    }
    if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', start); } else { start(); }
})();
